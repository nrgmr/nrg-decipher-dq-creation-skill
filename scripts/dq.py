def cmd_bump(args):
    package = guard_path(args.package)
    if not package.is_dir():
        die("%s is not a directory" % package)
    match = re.fullmatch(r"v(\d+)", package.name)
    if not match:
        die("%s is not a vN directory" % package)
    old = int(match.group(1))
    new = int(args.to) if args.to else old + 1
    if new <= old:
        die("--to must be greater than %d" % old)
    target = package.parent / ("v%d" % new)
    if target.exists():
        refuse("%s already exists" % target)

    name = package.parent.name
    plan = []
    for path in package_files(package):
        rel = path.relative_to(package).as_posix()
        new_rel = rel.replace("_v%d" % old, "_v%d" % new)
        plan.append((rel, new_rel))

    title = ""
    meta = package / "meta.xml"
    if meta.is_file():
        found = re.search(r"<title>(.*?)</title>",
                          meta.read_text(encoding="utf-8"), re.S)
        if found:
            title = found.group(1).strip()

    # Anchored rewrites only. An unanchored v<old> -> v<new> replacement
    # corrupts incidental matches; that is why the old tool needed diff review.
    patterns = [
        (re.compile(r"\b%s\.%d\b" % (re.escape(name), old)),
         "%s.%d" % (name, new)),
        (re.compile(r'("version"\s*:\s*)%d\b' % old), r"\g<1>%d" % new),
        (re.compile(r"\b%s v%d\b" % (re.escape(name), old)),
         "%s v%d" % (name, new)),
        (re.compile(r"\b%s_v%d\b" % (re.escape(name), old)),
         "%s_v%d" % (name, new)),
        (re.compile(r"(<version>)\s*%d\s*(</version>)" % old),
         r"\g<1>%d\g<2>" % new),
        (re.compile(r"\b%s-v%d-\b" % (re.escape(name.replace("_", "-")), old)),
         "%s-v%d-" % (name.replace("_", "-"), new)),
        (re.compile(r"\bv%d-host\b" % old), "v%d-host" % new),
        (re.compile(r"\b%sV%d\b" % ("".join(p.capitalize()
                                            for p in name.split("_")), old)),
         "%sV%d" % ("".join(p.capitalize() for p in name.split("_")), new)),
    ]
    if title:
        patterns.append((re.compile(r"\b%s v%d\b" % (re.escape(title), old)),
                         "%s v%d" % (title, new)))

    ambiguous = []
    for path in package_files(package):
        if path.suffix.lower() not in (".xml", ".js", ".css", ".json", ".md",
                                       ".txt"):
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for match in re.finditer(r"\bv%d\b" % old, text):
            window = text[max(0, match.start() - 40):match.end() + 40]
            if any(p.search(window) for p, _ in patterns):
                continue
            line = text.count("\n", 0, match.start()) + 1
            ambiguous.append("%s:%d  %s"
                             % (path.relative_to(package).as_posix(), line,
                                " ".join(window.split())[:70]))

    if not args.apply:
        print("dry run. v%d -> v%d in %s" % (old, new, package.parent))
        print("\nfiles (%d):" % len(plan))
        for rel, new_rel in plan:
            print("    %s%s" % (rel, "  ->  " + new_rel if rel != new_rel else ""))
        if ambiguous:
            print("\nambiguous v%d occurrences NOT rewritten (%d):"
                  % (old, len(ambiguous)))
            for item in ambiguous:
                print("    %s" % item)
            print("\nReview each. bump only rewrites anchored, enumerated sites; "
                  "an unanchored replacement is what corrupted incidental "
                  "matches before.")
        print("\nRe-run with --apply.")
        return OK

    target.mkdir(parents=True)
    for rel, new_rel in plan:
        out = target / new_rel
        out.parent.mkdir(parents=True, exist_ok=True)
        source = package / rel
        if source.suffix.lower() in (".xml", ".js", ".css", ".json", ".md",
                                     ".txt"):
            text = source.read_text(encoding="utf-8")
            for pattern, repl in patterns:
                text = pattern.sub(repl, text)
            out.write_text(text, encoding="utf-8", newline="\n")
        else:
            shutil.copyfile(source, out)
    print("created %s" % target)
    if ambiguous:
        print("\n%d ambiguous v%d occurrence(s) left alone. Review:"
              % (len(ambiguous), old))
        for item in ambiguous:
            print("    %s" % item)
    _extract(target, apply=True, quiet=True)
    print("\nNow run: python scripts/dq.py verify %s" % target)
    return OK


