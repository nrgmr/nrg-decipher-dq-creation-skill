def cmd_handoff(args):
    template = HANDOFFS.get(args.action)
    if template is None:
        die("unknown action %r. Available: %s"
            % (args.action, ", ".join(sorted(HANDOFFS))))
    print(template(args))
    return OK


def _manifest(package):
    rows, total = [], 0
    for path in package_files(package):
        rel = path.relative_to(package).as_posix()
        size = path.stat().st_size
        total += size
        rows.append("    %-46s %8d  %s" % (rel, size, sha256(path)[:16]))
    return rows, total


def _h_clone(args):
    if not args.source:
        die("--source <survey-id> is required")
    return """ACTION NEEDED (1 of 1)

In Decipher, duplicate survey %s/%s.
Do not edit %s itself.

Download the untouched duplicate to:
    incoming/<new-id>/

Send back: the new numeric survey ID.

Why: /lib/<dq>/vN is not compiled as a survey. A DQ can only run through a
sibling numeric survey that references its version.""" % (COMPANY,
                                                          args.source,
                                                          args.source)


def _h_upload_package(args):
    if not args.package:
        die("--package <dir> is required")
    package = guard_path(args.package)
    match = re.fullmatch(r"v(\d+)", package.name)
    if not match:
        die("%s is not a vN directory" % package)
    name = package.parent.name
    rows, total = _manifest(package)
    return """ACTION NEEDED (%s)

Upload as a whole directory, not file by file:
    local   %s/
    server  %s/lib/%s/%s/

%d files, %d bytes. Checksums below -- compare after upload.
Do not create a lib directory under %s.

Send back: confirmation, or any error text verbatim.

%s""" % (args.step or "1 of 1", package, SERVER_ROOT, name, package.name,
         len(rows), total, "/".join(FORBIDDEN) or "any other company",
         "\n".join(rows))


def _h_upload_survey(args):
    if not args.survey:
        die("--survey <id> is required")
    assets = args.asset or []
    asset_text = "\n".join("    %s" % a for a in assets) or "    none"
    return """ACTION NEEDED (%s)

Upload only this file:
    local   %s/%s/survey.xml
    server  %s/%s/survey.xml

Also upload these static assets the survey needs:
%s

Do not upload uids.bin, original.bin, the pickles, or any log -- those are the
server's, not ours.

Send back: confirmation, or any error text verbatim.""" % (
        args.step or "1 of 1", LOCAL_ROOT, args.survey, SERVER_ROOT,
        args.survey, asset_text)


def _h_compile(args):
    if not args.survey:
        die("--survey <id> is required")
    # Caller-supplied items are ADDED to the standing three, not substituted:
    # the standing three are what catch a package that looks fine.
    look = list(args.look or []) + [
        "radio buttons or text inputs visible anywhere on the page",
        "any configuration-error panel",
        "anything in the browser console",
    ]
    fresh = ("\n    Please use a fresh profile or a private window. A browser "
             "that has\n    already played media on this origin is allowed to "
             "autoplay with sound,\n    so it will hide the very failure this "
             "checks for.\n" if args.media else "")
    return """ACTION NEEDED (%s)

Compile survey %s in Decipher.

If it compiles, open it with a record assigned:
    https://%s/survey/selfserve/%s/%s?list=1

Look for, and tell me about any of these:
%s
%s
Send back: the compiler output verbatim if it failed, or the console text
verbatim if anything appeared there. Not a summary.

Why: the compiler names the exact element and attribute it rejected. A summary
loses the part I need.""" % (
        args.step or "1 of 1", args.survey, HOST, COMPANY, args.survey,
        "\n".join("    - %s" % item for item in look), fresh)


def _h_state(args):
    if not args.survey:
        die("--survey <id> is required")
    return """ACTION NEEDED (%s)

Set survey %s to state="testing".

Why: dev mode does not create respondent records, so there is no exported data
to check against. Data acceptance needs testing state.

Send back: confirmation.""" % (args.step or "1 of 1", args.survey)


def _h_export(args):
    if not args.survey:
        die("--survey <id> is required")
    fixture = "\n".join("    %s" % f for f in (args.fixture or
                                               ["<exact ordered actions>"]))
    return """ACTION NEEDED (%s)

After running the fixture below, export the data for survey %s and send the row
for that respondent.

Fixture:
%s

Send back: the exported row, or the file.

Why: a correct screen does not prove a correct dataset. Hidden inputs can look
right and still be discarded on submit, so the export is the only evidence that
settles it.""" % (args.step or "1 of 1", args.survey, fixture)


HANDOFFS = {
    "clone": _h_clone,
    "upload-package": _h_upload_package,
    "upload-survey": _h_upload_survey,
    "compile": _h_compile,
    "state": _h_state,
    "export": _h_export,
}


# -------------------------------------------------------------------------- scan

def cmd_scan(args):
    root = guard_path(args.root)
    pattern = re.compile(r'uses="%s\.(\d+)"' % re.escape(args.name))
    hits = []
    for path in sorted(root.rglob("survey.xml")):
        text = path.read_text(encoding="utf-8", errors="replace")
        versions = sorted(set(pattern.findall(text)))
        if not versions:
            continue
        rel = path.relative_to(root).as_posix()
        own = "/lib/%s/v" % args.name in "/" + rel
        hits.append({"survey": rel, "versions": versions,
                     "is_own_demo": own})
    if args.json:
        print(json.dumps({"dq": args.name, "references": hits,
                          "count": len([h for h in hits
                                        if not h["is_own_demo"]])}, indent=2))
        return OK
    print("references to %s under %s" % (args.name, root))
    for hit in hits:
        tag = "  (own demo)" if hit["is_own_demo"] else ""
        print("    %-56s %s%s" % (hit["survey"],
                                  ", ".join("v" + v for v in hit["versions"]),
                                  tag))
    adopters = [h for h in hits if not h["is_own_demo"]]
    print("\n%d adopting survey(s) found locally." % len(adopters))
    print("Local only. This cannot see the server, so zero is not proof of "
          "zero adopters.")
    return OK


