def build_parser():
    parser = argparse.ArgumentParser(
        prog="dq.py", description="Decipher DQ prototyping tools")
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("new", help="scaffold a package from an archetype")
    p.add_argument("--archetype", required=True)
    p.add_argument("--spec")
    p.add_argument("--name")
    p.add_argument("--into", default="test_environment/lib")
    p.add_argument("--questions", action="store_true",
                   help="print the archetype's interview and exit")
    p.add_argument("--apply", action="store_true")
    p.set_defaults(func=cmd_new)

    p = sub.add_parser("verify", help="run every local check")
    p.add_argument("package")
    p.add_argument("--only", action="append",
                   help="check or group name; repeatable")
    p.add_argument("--skip", action="append")
    p.add_argument("--json", action="store_true")
    p.set_defaults(func=cmd_verify)

    p = sub.add_parser("extract",
                       help="regenerate fragments and IMPORT.md from the demo")
    p.add_argument("package")
    p.add_argument("--apply", action="store_true")
    p.set_defaults(func=cmd_extract)

    p = sub.add_parser("bump", help="fork vN to vN+1")
    p.add_argument("package")
    p.add_argument("--to")
    p.add_argument("--apply", action="store_true")
    p.set_defaults(func=cmd_bump)

    p = sub.add_parser("handoff", help="emit one exact human action")
    p.add_argument("action", choices=sorted(HANDOFFS))
    p.add_argument("--package")
    p.add_argument("--survey")
    p.add_argument("--source")
    p.add_argument("--step", help='e.g. "1 of 2"')
    p.add_argument("--asset", action="append")
    p.add_argument("--look", action="append")
    p.add_argument("--fixture", action="append")
    p.add_argument("--media", action="store_true",
                   help="add the fresh-profile warning for media DQs")
    p.set_defaults(func=cmd_handoff)

    p = sub.add_parser("scan", help="find local surveys using a DQ")
    p.add_argument("--name", required=True)
    p.add_argument("--root", default="test_environment")
    p.add_argument("--json", action="store_true")
    p.set_defaults(func=cmd_scan)

    return parser


def main(argv=None):
    args = build_parser().parse_args(argv)
    try:
        return args.func(args)
    except SystemExit:
        raise
    except FileNotFoundError as exc:
        die(str(exc))
    except json.JSONDecodeError as exc:
        die("invalid JSON: %s" % exc)


if __name__ == "__main__":
    sys.exit(main())
